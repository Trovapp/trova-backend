-- #547 / ADR 0059. Hibernate ddl-auto:update 매핑과 같은 참고 DDL.
-- 이 작업에서 운영/개발 DB에 실행하지 않았다. 기존 데이터는 동의나 이벤트를 소급 생성하지 않는다.
BEGIN;
CREATE TABLE IF NOT EXISTS public.analytics_consents (
    user_id bigint PRIMARY KEY,
    revision bigint NOT NULL,
    usage_consent boolean NOT NULL,
    transfer_consent boolean NOT NULL,
    analytics_id uuid UNIQUE,
    updated_at timestamp without time zone NOT NULL,
    last_put_revision bigint
);
CREATE TABLE IF NOT EXISTS public.analytics_deletion_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analytics_id uuid NOT NULL UNIQUE,
    status varchar(20) NOT NULL,
    created_at timestamp without time zone NOT NULL
);
ALTER TABLE public.trip_members ADD COLUMN IF NOT EXISTS analytics_event_id uuid;
ALTER TABLE public.trip_share_links ADD COLUMN IF NOT EXISTS analytics_event_id uuid;

-- ADR 0048: 기본 이벤트 트리거와 별개로 명시 적용 시에도 직접 API 노출을 막는다.
ALTER TABLE public.analytics_consents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analytics_deletion_jobs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.analytics_consents FROM anon, authenticated;
REVOKE ALL ON TABLE public.analytics_deletion_jobs FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.analytics_deletion_jobs_id_seq FROM anon, authenticated;
COMMIT;
